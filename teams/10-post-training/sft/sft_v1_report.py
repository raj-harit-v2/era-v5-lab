#!/usr/bin/env python3
"""Build `sft/results/sft_v1_token_records.md` and the C3 record JSONL for `mix_inventory.py --c3-records`.

    python sft_v1_report.py --records-dir <dir of *.record.json> --worklist worklist.json \
        --out-md ../results/sft_v1_token_records.md --out-c3-jsonl c3_records.jsonl [--bench-csv bench.csv]

Reads only the records (counts, hashes, timings) and the work list. No dataset text is read or printed.
Every figure in the Markdown carries its scope: "first 1,000 rows" or "full set".
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

MAXLEN = 32768


def n(x) -> str:
    return "n/a" if x is None else f"{int(x):,}"


def unk(value, fmt=str) -> str:
    """A runtime figure, or `unknown` where the record could not measure it (a finalized run); never 0."""
    return "unknown" if value is None else fmt(value)


def short_reason(text: str) -> str:
    text = text.replace("trajectory did not resolve the issue (resolved != 1)", "unresolved trajectory")
    text = text.replace("trace over the 64k effort budget", "trace over 64k")
    text = text.replace("generation did not finish (finish_reason != stop)", "generation not finished")
    text = text.replace("row has no messages (statement only)", "statement only, no messages")
    if text.startswith("content contains"):
        text = "content holds a literal chat marker"
    return text


def skips(rec: dict) -> str:
    return "; ".join(f"{short_reason(k)} {v}" for k, v in rec["skipped"].items()) or "none"


def load(records_dir: Path, suffix: str) -> dict[str, dict]:
    return {p.name[: -len(suffix)]: json.loads(p.read_text(encoding="utf-8")) for p in sorted(records_dir.glob(f"*{suffix}"))}


def c3_record(rec: dict, scope_label: str, admission: str) -> dict:
    c = rec["checks"]
    return {"set_id": rec["set"], "scope": scope_label, "status": rec.get("status") or "measurement", "admission": admission,
            "rows_in": rec["rows_in"], "rows": rec["rows_out"], "skipped": sum(rec["skipped"].values()),
            "sequence_tokens": c["tokens"], "trained_tokens": c["trained_tokens"],
            "shifted_supervised_targets": c["shifted_supervised_targets"], "tokenizer_sha256": rec["tokenizer_sha256"],
            "content_sha256": rec["content_sha256"], "length": c["length"], "effort": rec["effort_manifest"],
            "rows_over_max_len": c["rows_over_max_len"], "max_len": c["max_len"],
            "checks_ok": bool(c["checks_ok"] and rec.get("deterministic_rerun") is not False),
            "hub_revision": rec.get("hub_revision"), "rows_per_s": rec.get("rows_per_s_convert")}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--records-dir", type=Path, required=True)
    ap.add_argument("--worklist", type=Path, required=True)
    ap.add_argument("--out-md", type=Path, required=True)
    ap.add_argument("--out-c3-jsonl", type=Path, required=True)
    ap.add_argument("--bench-csv", type=Path)
    ap.add_argument("--bench-matched-csv", type=Path, help="old and new convert.py at the same thread count on the same saved input")
    ap.add_argument("--run-notes", type=Path, help="JSON with hand-recorded run state (proofs run, interrupted run, job requests)")
    ap.add_argument("--extra-md", type=Path, help="Markdown inserted before the reproduce section (run notes written by hand)")
    a = ap.parse_args()
    wl = json.loads(a.worklist.read_text(encoding="utf-8"))
    by_set = {r["set"]: r for r in wl["sets"]}
    first = load(a.records_dir, ".record.json")
    first = {k: v for k, v in first.items() if not k.endswith(".full") and "first" in v["scope"]}
    full = {k[: -len(".full")]: v for k, v in load(a.records_dir, ".full.record.json").items()}
    first = {v["set"]: v for v in first.values()}
    full = {v["set"]: v for v in full.values()}
    tok = next(iter(first.values()))["tokenizer_sha256"]
    admission = lambda s: "allowed by licence table; not a pack" if by_set[s]["decision_class"] == "allowed" else "TSAI reserves; not admitted; measurement only"

    L = []
    w = L.append
    w("# SFT data v1 under C3: token records for the rest of the mix (WP14)")
    w("")
    w(f"Tokenizer: C3, `tokenizer.json` sha256 `{tok}`. Context limit for the over-length column: {MAXLEN:,} tokens "
      "(`max_sequence_tokens`, provisional for SFT data v1). Rendering and masks: `chat-format/render.py` and "
      "`sft/convert.py` unchanged in meaning (see `convert_report.md`). Generated by `sft/sft_v1_report.py` from the "
      "per-set records in `sft/results/sft_v1_records/`; no dataset text appears here.")
    w("")
    w("**How to read the labels.** `first 1,000 rows` = the first 1,000 *selected* rows of the set in source order, read "
      "from the pinned Hub revision: a prefix, not a sample of the whole set, so effort mix and lengths can differ a lot "
      "from the full set (several sets are sorted by source or difficulty). `full` = every row the adapter produced from the "
      "pinned files. None of these outputs has been through the decontamination run, so they are **converted, not "
      "decontaminated**, and **none is a pack**. A set the licence table lists as `TSAI reserves` is **not admitted**; its "
      "record is a measurement only. OCR-2 is the WP1 pack and is not converted or counted here.")
    w("")
    w("## 1. Work list")
    w("")
    lists = wl["lists"]
    w(f"Built by `sft/sft_v1_worklist.py` from `convert.py` ADAPTERS ({wl['counts']['adapters']}), the Stage 1 licence "
      f"table ({wl['counts']['stage1_sets']} sets) and the #391 proposal `sft_mix_proposal.md`. Input hashes: "
      + ", ".join(f"`{k}` `{v[:12]}…`" for k, v in wl["inputs_sha256"].items()) + ".")
    w("")
    w(f"- **Allowed + adapter + in the proposal ({len(lists['allowed'])}):** " + ", ".join(f"`{s}`" for s in lists["allowed"]) + ".")
    w(f"- **TSAI reserves + adapter + in the proposal, no data-rule flag ({len(lists['reserved'])}, measurement only):** "
      + ", ".join(f"`{s}`" for s in lists["reserved"]) + ".")
    w(f"- **Owned by WP1 ({len(lists['owned'])}):** " + ", ".join(f"`{s}`" for s in lists["owned"]) + ".")
    w(f"- **Held for a data-rule ruling ({len(lists['hold'])}):** " + ", ".join(f"`{s}`" for s in lists["hold"]) + ".")
    w(f"- **Out of the work list ({len(lists['out'])}):** see the reasons below.")
    w("")
    w("### Held sets and why")
    w("")
    w("| Set | Decision | Flag | Evidence |")
    w("|---|---|---|---|")
    for s in lists["hold"]:
        r = by_set[s]
        w(f"| `{s}` | {r['decision'][:30]} | {', '.join(r['flags'])} | {r['generator'][:260]} |")
    w("")
    w("A flag is a reading of the licence table's generator column against the TSAI data rule, not a ruling. A held set is not "
      "converted and not admitted until TSAI rules.")
    w("")
    w("### Sets that fall out, by reason")
    w("")
    groups: dict[str, list[str]] = {}
    for r in wl["sets"]:
        if r["track"] != "out":
            continue
        key = "; ".join(x for x in r["reasons"])
        groups.setdefault(key, []).append(r["set"])
    w("| Reason | Count | Sets |")
    w("|---|---:|---|")
    for key, sets in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        w(f"| {key} | {len(sets)} | " + ", ".join(f"`{s}`" for s in sets) + " |")
    w("")
    w("### Provenance caveats recorded in the licence table (not blockers by themselves)")
    w("")
    w("| Set | Licence state | Caveat (sentence from `licence_table.md`) |")
    w("|---|---|---|")
    for s in lists["allowed"] + lists["reserved"]:
        for cav in by_set[s].get("licence_table_caveats", []):
            w(f"| `{s}` | {by_set[s]['decision_class']} | {cav} |")
    w("")
    w("### Pinned sources")
    w("")
    w("| Set | Hub dataset | Revision (commit) | Card licence tag | Gated |")
    w("|---|---|---|---|---|")
    for s in lists["allowed"] + lists["reserved"] + lists["hold"]:
        r = by_set[s]
        h = r.get("hf") or {}
        w(f"| `{s}` | {r['source']} | `{(h.get('sha') or 'n/a')}` | {h.get('card_licence') or 'n/a'} | {h.get('gated')} |")
    w("")
    w("Generator model and licence for every set are in `licences/licence_table.md` (Stage 1) and are copied into each "
      "record. Revisions come from the public Hub metadata API on the run date; file sizes and LFS sha256 per file are "
      "in the private pin file used for the runs and are listed in each full-run record where files were read in full.")
    w("")
    w("## 2. First 1,000 rows, C3")
    w("")
    w("Every number in this table is `first 1,000 rows, C3` (rows in = 1,000 selected rows). `targets` are loss-masked "
      "assistant tokens after the one-token shift; `share` = targets / tokens. `over` = rows longer than 32,768 tokens "
      "(counted, not removed). Effort tiers are the smallest of 1k / 4k / 16k / 64k that holds the row's think + "
      "tool-call + tool-result trace.")
    w("")
    w("| Set | Licence state | Rows out | Skips | Effort 1k / 4k / 16k / 64k | Tokens | Targets | Share | p50 / p95 / max | Over 32,768 | content_sha256 |")
    w("|---|---|---:|---|---|---:|---:|---:|---|---:|---|")
    order = lists["allowed"] + lists["reserved"]
    for s in order:
        if s not in first:
            w(f"| `{s}` | {by_set[s]['decision_class']} | not run | | | | | | | | |")
            continue
