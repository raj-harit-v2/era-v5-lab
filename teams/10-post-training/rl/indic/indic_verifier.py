"""Binary reward for Indic short-answer tasks: an exact check on the final answer. No candidate code is run.

    reward(task_dir, completion) -> {"reward": 0 | 1, "reason": str, "task_id": str}
    score(task, completion)      -> the same, for a task already prepared with prepare() (generate.py items)

The model answers in the task's language and gives its final answer in exactly one `<answer>...</answer>` in the
visible reply. Everything up to the last `<|/think|>` (the chat format's end-of-thinking marker) is ignored, and a
reply whose think span is never closed has no answer.

Normalisation, applied to the model's answer and to every accepted answer (the G10 text rule of
swe-task/hindi_text_prep.py, plus what an exact check needs):
  * remove U+200B and U+FEFF only. ZWJ and ZWNJ stay: they choose between a conjunct and a half form;
  * case folding (only Latin letters change), then Unicode NFC (not NFKC), so a decomposed nukta or vowel sign
    equals the composed form;
  * runs of whitespace become one space; quotes, brackets and the end marks . , ; : ! ? । ॥ are stripped at the ends.

Answer types (answer_type in task.json; the accepted answers are in answer.json and never in the prompt):
  integer  ASCII digits or the task's own script's digits (Devanagari for a Hindi task, Tamil for a Tamil task, ...),
           optionally grouped as 1,00,000 or 100,000, with an optional minus sign. "४२" equals "42" on a Hindi task.
           Mixed scripts ("4२"), another script's digits ("٤٢"), a leading zero ("042"), units and words score 0.
  text     equal to one accepted variant, and every letter and mark is in the task's script, so a Hindi answer
           written in Latin letters scores 0.
  choice   one of the option labels in task.json "choices" (for example क ख ग घ).

Why a policy cannot game it:
  * two different answers score 0, so it cannot hedge; the same answer repeated is fine;
  * an answer longer than MAX_ANSWER_CHARS scores 0, so it cannot put a list of guesses into one tag;
  * only the last MAX_SCAN_CHARS of the visible reply are read, so a huge completion costs as much as a short one;
  * the reply dict never contains the expected answer, only a reason.

CLI:
    python indic_verifier.py --reward <task_dir> <completion.txt>
    python indic_verifier.py --check-task <task_dir>     # lint: accepted answers score 1, the listed wrong ones 0
    python indic_verifier.py --check-all                 # --check-task for every folder in tasks/
    python indic_verifier.py --bench [--n 200000]        # completions scored per second on one core
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import unicodedata
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASKS = HERE / "tasks"
MAX_SCAN_CHARS = 20_000
MAX_ANSWER_CHARS = 200
THINK_START, THINK_END = "<|think|>", "<|/think|>"
TYPES = ("integer", "text", "choice")
DIFFICULTIES = ("easy", "medium", "hard")
ELIGIBILITY = ("eval", "train")

_STRIP = {0x200B: None, 0xFEFF: None}
_EDGE = " .,;:!?\"'()[]{}\u0964\u0965\u201c\u201d\u2018\u2019"
_ANSWER = re.compile(r"<answer>(.*?)</answer>", re.DOTALL)
_WS = re.compile(r"\s+")
_INT = re.compile(r"[-\u2212]?(?:\d{1,3}(?:,\d{2})*,\d{3}|\d{1,3}(?:,\d{3})+|\d+)")  # \d: any script's digits
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
_MODEL_WRITTEN = re.compile(r"claude|\bai\b|assistant|gpt|gemini|llama|\bllm\b|model[- ]written|generated by",
                            re.IGNORECASE)

# Unicode blocks per ISO 15924 script code. Letters and marks of a text answer must all come from its script.
SCRIPTS = {
    "Deva": ((0x0900, 0x097F), (0xA8E0, 0xA8FF), (0x1CD0, 0x1CFF)),
    "Beng": ((0x0980, 0x09FF),),
    "Guru": ((0x0A00, 0x0A7F),),
    "Gujr": ((0x0A80, 0x0AFF),),
    "Orya": ((0x0B00, 0x0B7F),),
    "Taml": ((0x0B80, 0x0BFF), (0x11FC0, 0x11FFF)),
    "Telu": ((0x0C00, 0x0C7F),),
    "Knda": ((0x0C80, 0x0CFF),),
    "Mlym": ((0x0D00, 0x0D7F),),
    "Latn": ((0x0041, 0x005A), (0x0061, 0x007A), (0x00C0, 0x024F), (0x1E00, 0x1EFF)),
}
_SCRIPT_CHARS = {k: frozenset(chr(c) for lo, hi in v for c in range(lo, hi + 1)) for k, v in SCRIPTS.items()}
# The digit zero of each script. An integer answer may use ASCII digits or its task's own digits.
DIGIT_ZERO = {"Deva": 0x966, "Beng": 0x9E6, "Guru": 0xA66, "Gujr": 0xAE6, "Orya": 0xB66, "Taml": 0xBE6,
              "Telu": 0xC66, "Knda": 0xCE6, "Mlym": 0xD66, "Latn": 0x30}


# --- text --------------------------------------------------------------------------------------

def normalise(text: str) -> str:
    text = unicodedata.normalize("NFC", text.translate(_STRIP).casefold())
    return _WS.sub(" ", text).strip(_EDGE)


def visible_reply(completion: str) -> str | None:
    """The part of the completion after the last end-of-thinking marker, or None if thinking never closed."""
    text = completion or ""
    end = text.rfind(THINK_END)
    if end >= 0:
        text = text[end + len(THINK_END):]
    if THINK_START in text:
        return None
    return text[-MAX_SCAN_CHARS:]


def extract_answers(completion: str) -> tuple[set[str] | None, str]:
    """(the distinct normalised answers, "ok") or (None, reason)."""
    reply = visible_reply(completion)
    if reply is None:
        return None, "think span not closed"
    found = _ANSWER.findall(reply)
    if not found:
        return None, "no answer tag"
    if any(len(a) > MAX_ANSWER_CHARS for a in found):
        return None, "answer too long"
    answers = {normalise(a) for a in found}
    return (answers, "ok") if all(answers) else (None, "empty answer")


def parse_integer(s: str, script: str | None = None) -> int | None:
    """The value of a normalised integer answer, or None. All digits must come from one script.

    With a script (scoring an answer): the digits are ASCII or that script's own, and there is no leading zero, so a
    Hindi task takes 40 or ४० but not ٤٠, ４０ or 040. Without one (finding an answer written in a prompt): digits of
    any one script and leading zeros count, so a leak is found whatever way it is written.
    """
    if not _INT.fullmatch(s):
        return None
    zeros = {ord(c) - unicodedata.decimal(c) for c in s if c.isdecimal()}
    if len(zeros) != 1:
        return None
    if script is not None:
        if zeros.pop() not in (0x30, DIGIT_ZERO[script]):
            return None
        body = s.lstrip("-\u2212").replace(",", "")
        if len(body) > 1 and unicodedata.decimal(body[0]) == 0:
            return None
    return int(s.replace(",", "").replace("\u2212", "-"))


def outside_script(s: str, script: str) -> bool:
    allowed = _SCRIPT_CHARS[script]
    return any(unicodedata.category(ch)[0] in "LM" and ch not in allowed for ch in s)


# --- tasks -------------------------------------------------------------------------------------

def prepare(meta: dict, accepted: list) -> dict:
    """The fields score() needs, with the accepted answers normalised once."""
    kind = meta.get("answer_type")
    if kind == "integer":
        keys = frozenset(accepted)
    elif kind in ("text", "choice"):
        keys = frozenset(normalise(a) for a in accepted)
    else:
        raise ValueError(f"unknown answer_type {kind!r}")
    return {"id": meta.get("id"), "answer_type": kind, "script": meta.get("script"), "accepted": keys}


@lru_cache(maxsize=4096)
def _load(path: str, stamp: tuple) -> dict:
    d = Path(path)
    meta = json.loads((d / "task.json").read_text(encoding="utf-8"))
    answer = json.loads((d / "answer.json").read_text(encoding="utf-8"))
    return prepare(meta, answer.get("accepted", []))


def load_task(task_dir: Path | str) -> dict:
    """Prepared task, cached until task.json or answer.json changes on disk."""
    d = Path(task_dir).resolve()
    stamp = tuple((s.st_mtime_ns, s.st_size) for s in ((d / f).stat() for f in ("task.json", "answer.json")))
    return _load(str(d), stamp)


# --- the reward --------------------------------------------------------------------------------

def score(task: dict, completion: str) -> dict:
    out = {"task_id": task["id"], "reward": 0}
    answers, why = extract_answers(completion)
    if answers is None:
        return {**out, "reason": why}
    if task["answer_type"] == "integer":
        values = {parse_integer(a, task["script"]) for a in answers}  # "40" and "४०" are one answer
        if None in values:
            return {**out, "reason": "answer is not an integer"}
        answers = values
    if len(answers) > 1:
        return {**out, "reason": "more than one answer"}
    answer = answers.pop()
    if task["answer_type"] == "text" and outside_script(answer, task["script"]):
        return {**out, "reason": "answer is not in the task's script"}
    ok = answer in task["accepted"]
    return {**out, "reward": int(ok), "reason": "correct" if ok else "wrong answer"}


def reward(task_dir: Path | str, completion: str) -> dict:
    return score(load_task(task_dir), completion)


def wrap(answer) -> str:
    """A short visible reply ending in the given answer: how a test or known_outputs() writes a completion."""
    return f"उत्तर नीचे है।\n<answer>{answer}</answer>\n"


def known_outputs(task_dir: Path | str) -> tuple[str, str]:
    """(a completion that must score 1, one that must score 0), from answer.json."""
    answer = json.loads((Path(task_dir) / "answer.json").read_text(encoding="utf-8"))
    return wrap(answer["accepted"][0]), wrap(answer["wrong"][0])


# --- task lint ---------------------------------------------------------------------------------

def _values_ok(kind: str, values) -> bool:
    if not isinstance(values, list) or not values:
        return False
    if kind == "integer":
        return all(type(v) is int for v in values)
    return all(isinstance(v, str) for v in values)


def answer_in_prompt(prompt: str, kind: str, accepted: list, allowed: bool = False) -> bool:
    """True if the prompt gives the answer away: an accepted integer written in any script, or an accepted text
    answer (unless the task is a span task, allowed=True). Choice labels are always in the prompt."""
    if kind == "integer":
        return bool({parse_integer(m.group()) for m in _INT.finditer(unicodedata.normalize("NFC", prompt))} & set(accepted))
    if kind == "text" and not allowed:
        flat = normalise(prompt)
        return any(normalise(a) in flat for a in accepted)
    return False


def check_task(task_dir: Path | str) -> list[str]:
    """Problems with a task folder (empty list = fine)."""
    d = Path(task_dir)
    problems = [f"missing {f}" for f in ("task.json", "prompt.md", "answer.json") if not (d / f).is_file()]
    if problems:
        return problems
    meta = json.loads((d / "task.json").read_text(encoding="utf-8"))
    answer = json.loads((d / "answer.json").read_text(encoding="utf-8"))
    prompt = (d / "prompt.md").read_text(encoding="utf-8")
    for key in ("id", "title", "language", "script", "answer_type", "difficulty", "source", "author", "eligibility"):
        if not meta.get(key):
            problems.append(f"task.json lacks {key}")
    if meta.get("id") != d.name or not _NAME.match(d.name):
        problems.append("task.json id differs from the folder name, or the name has characters other than A-Z a-z 0-9 _ . -")
    if meta.get("script") not in SCRIPTS:
        problems.append(f"script must be one of {sorted(SCRIPTS)}")
    kind = meta.get("answer_type")
    if kind not in TYPES:
        problems.append(f"answer_type must be one of {TYPES}")
    if meta.get("difficulty") not in DIFFICULTIES:
        problems.append(f"difficulty must be one of {DIFFICULTIES}")
    if meta.get("eligibility") not in ELIGIBILITY:
        problems.append(f"eligibility must be one of {ELIGIBILITY}")
    source = str(meta.get("source", ""))
    if not source.lower().startswith("original"):
        problems.append('source must start with "original" and name the author')
    if meta.get("eligibility") == "train":  # TSAI data rule, 3 Nov: training text is written by people
        if _MODEL_WRITTEN.search(source):
            problems.append("a train task must be written by a person; its source names a model")
        reviewer = str(meta.get("team2_reviewer", "")).strip()
        if not reviewer or reviewer == meta.get("author"):
            problems.append("a train task needs a team2_reviewer who is not the author")
    if "<answer>" not in prompt:
        problems.append("prompt.md must ask for the final answer in <answer>...</answer>")
    if problems:
        return problems

    accepted, wrong = answer.get("accepted"), answer.get("wrong")
    if not _values_ok(kind, accepted):
        problems.append(f"answer.json accepted must be a non-empty list of {'ints' if kind == 'integer' else 'strings'}")
    if not _values_ok(kind, wrong):
        problems.append(f"answer.json wrong must be a non-empty list of {'ints' if kind == 'integer' else 'strings'}")
    if problems:
        return problems
    norm = (lambda v: v) if kind == "integer" else normalise
    if {norm(a) for a in accepted} & {norm(w) for w in wrong}:
        problems.append("an answer is both accepted and wrong")
    if kind != "integer" and not all(norm(a) for a in accepted):
        problems.append("an accepted answer is empty after normalisation")
    if kind == "text" and any(outside_script(normalise(a), meta["script"]) for a in accepted):
        problems.append("an accepted answer has letters outside the task's script")
    if kind == "choice":
        choices = meta.get("choices")
        labels = {normalise(c) for c in choices} if isinstance(choices, list) else set()
        if len(labels) < 2 or len(labels) != len(choices):
            problems.append("task.json choices must list two or more distinct labels")
        elif not {normalise(a) for a in accepted} <= labels:
            problems.append("an accepted answer is not one of the choices")
    if answer_in_prompt(prompt, kind, accepted, bool(meta.get("answer_in_prompt"))):
        problems.append('an accepted answer appears in prompt.md (set "answer_in_prompt": true for span tasks)')
    if problems:
        return problems

    task = load_task(d)
    for a in accepted:
        r = score(task, wrap(a))
        if r["reward"] != 1:
            problems.append(f"an accepted answer does not score 1: {r['reason']}")
    for w in wrong:
        if score(task, wrap(w))["reward"] != 0:
            problems.append("a wrong answer scores 1")
    return problems


def check_all(tasks_dir: Path = TASKS) -> dict[str, list[str]]:
    return {p.parent.name: check_task(p.parent) for p in sorted(tasks_dir.glob("*/task.json"))}


# --- benchmark ---------------------------------------------------------------------------------

def bench(n: int = 200_000, tasks_dir: Path = TASKS) -> dict:
    """Score n completions (half correct, half wrong) with ~2 KB of reasoning and a think span each."""
    thinking = THINK_START + "\n" + "सोचते हैं: पहले संख्याएँ जोड़ते हैं, फिर घटाते हैं। " * 30 + "\n" + THINK_END + "\n"
    work = []
    for p in sorted(tasks_dir.glob("*/task.json")):
        good, bad = known_outputs(p.parent)
        task = load_task(p.parent)
        work += [(task, thinking + good), (task, thinking + bad)]
    if not work:
        raise SystemExit(f"no tasks in {tasks_dir}")
    rewards = 0
    t0 = time.perf_counter()
    for i in range(n):
        task, completion = work[i % len(work)]
        rewards += score(task, completion)["reward"]
    seconds = time.perf_counter() - t0
    return {"completions": n, "seconds": round(seconds, 3), "per_second": round(n / seconds),
            "mean_completion_chars": round(sum(len(c) for _, c in work) / len(work)), "rewards": rewards}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--reward", nargs=2, metavar=("TASK_DIR", "COMPLETION_FILE"))
    ap.add_argument("--check-task", metavar="TASK_DIR")
    ap.add_argument("--check-all", action="store_true")
    ap.add_argument("--bench", action="store_true")
    ap.add_argument("--n", type=int, default=200_000)
    args = ap.parse_args(argv)
    if args.reward:
        task_dir, comp = args.reward
        for what, path in (("task folder", Path(task_dir) / "task.json"), ("completion file", Path(comp))):
            if not path.is_file():
                print(f"{what} not found: {path.parent if what == 'task folder' else path}", file=sys.stderr)
                return 2
        print(json.dumps(reward(task_dir, Path(comp).read_text(encoding="utf-8")), ensure_ascii=False))
        return 0
    if args.check_task:
        if not (Path(args.check_task) / "task.json").is_file():
            print(f"task folder not found: {args.check_task}", file=sys.stderr)
            return 2
        problems = check_task(args.check_task)
        print("\n".join(problems) if problems else "task OK")
        return 1 if problems else 0
    if args.check_all:
        results = check_all()
        for name, problems in results.items():
            print(f"{name}: {'; '.join(problems) if problems else 'OK'}")
        return 1 if any(results.values()) else 0
    if args.bench:
        print(json.dumps(bench(args.n)))
        return 0
    ap.error("give --reward, --check-task, --check-all or --bench")
    return 2


if __name__ == "__main__":
    sys.exit(main())
