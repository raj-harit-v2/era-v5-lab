"""Binary reward for tool-result tasks: the reply must report the tool's output exactly. No candidate code is run.

    reward(task_dir, completion) -> {"reward": 0 | 1, "reason": str, "task_id": str}
    prompt_text(task_dir)        -> the text the model is given: the transcript up to `<|im_start|>assistant\\n`

A task is a chat-format v0 transcript that ends with a tool result. The model must answer the user from that result.
The completion is what the model wrote after `<|im_start|>assistant\\n`; the closing `<|im_end|>` and `<|endoftext|>`
are optional. It scores 1 only if all of these hold:
  0. it is text: a string of valid Unicode with no control character other than tab and newline (NUL, an ANSI colour
     code and a lone surrogate score 0);
  1. it is exactly one assistant turn of chat format v0 (read with chat-format/render.py): no made-up tool or user
     turn, no look-alike markers such as `<tool_call>`, and a think span that is closed;
  2. it makes no tool call: the answer is already in the transcript;
  3. the visible reply (the think span is not read) is not empty and has at most MAX_REPLY_CHARS characters;
  4. every `required` value of hidden/expected.json appears in the reply as a whole value;
  5. no `wrong` value of hidden/expected.json appears in the reply as a whole value.

hidden/expected.json is the ground truth. The model never sees it: prompt_text() renders only messages.json. A broken
hidden/expected.json (not JSON, a duplicate key, an empty or non-list `required` or `wrong`, a value that is both)
raises ValueError, and a missing one FileNotFoundError: a task error never looks like a model's wrong answer.

Exact text: letter case, digits, units and spelling must match the tool's text. Only these are evened out, on both
sides: Unicode NFC (two encodings of one Indic letter agree; never NFKC); the removal of invisible characters that
never change a value: U+200B and U+FEFF (the G10 text rule in swe-task/hindi_text_prep.py) and every other format
character (soft hyphen, word joiner, direction marks), variation selectors and the combining grapheme joiner; the
removal of a ZWJ or ZWNJ that follows no letter it can join (after a digit, a Latin letter or a space: `3<ZWJ>1` is
`31`), while inside an Indic word a joiner is kept; and runs of whitespace read as one space.

A whole value is not part of a longer word or number: `31.6` is found in "It is 31.6 °C." but not in "131.6", "31.65"
or "-31.6", and `31` is not found inside "31.6".

`required` values are copied from the tool result. `wrong` values are altered copies (rounded, retyped, a joiner
dropped, a unit changed) that never appear in the tool result. A reply may quote other values of the tool result.

A reply cut off by the length limit is scored on what it holds: cut inside a value, the think span or a tool call, it
scores 0. The RL reward view drops `<|im_end|>` (rl-loop/team5_adapter.py, keep_stop=False), so a finished reply and
one cut after the full value look the same here; the trainer knows which replies hit the limit.

Limit: this checks values, not meaning. "It is not 31.6 °C" scores 1. Judging meaning needs a judge model.

CLI:
    python toolresult_verifier.py --reward <task_dir> <completion.txt>
    python toolresult_verifier.py --prompt <task_dir>        # the text the model is given
    python toolresult_verifier.py --check-task <task_dir>    # lint: required values score 1, wrong ones 0
    python toolresult_verifier.py --check-all                # --check-task for every folder in tasks/
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
import unicodedata
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASKS = HERE / "tasks"
TEAM = HERE.parent.parent
MAX_REPLY_CHARS = 1_000
EXPECTED = "hidden/expected.json"  # the ground truth of a task, never part of the prompt
TASK_FILES = ("task.json", "messages.json", EXPECTED)
DIFFICULTIES = ("easy", "medium", "hard")
ELIGIBILITY = ("eval", "train")

JOINERS = "‌‍"  # ZWNJ, ZWJ: inside an Indic word they change its spelling, so there they are kept
_WS = re.compile(r"\s+")
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]")  # C0 and C1 controls except tab, newline, CR
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
_MODEL_WRITTEN = re.compile(r"claude|\bai\b|assistant|gpt|gemini|llama|\bllm\b|model[- ]written|generated by",
                            re.IGNORECASE)


def _load_render():
    """chat-format/render.py, loaded by path (no __pycache__ left in the repo)."""
    spec = importlib.util.spec_from_file_location("g10_toolresult_render", TEAM / "chat-format" / "render.py")
    module = importlib.util.module_from_spec(spec)
    keep, sys.dont_write_bytecode = sys.dont_write_bytecode, True
    try:
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = keep
    return module


render = _load_render()
T = render.T


# --- text --------------------------------------------------------------------------------------

class _Invisible(dict):
    """str.translate table that deletes the invisible characters which never change a value: format characters (Cf)
    other than ZWJ and ZWNJ, variation selectors and the combining grapheme joiner. Filled one code point at a time."""

    def __missing__(self, cp: int):
        ch = chr(cp)
        drop = ((unicodedata.category(ch) == "Cf" and ch not in JOINERS) or cp == 0x034F
                or 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF)
        self[cp] = None if drop else cp
        return self[cp]


_INVISIBLE = _Invisible()


def _joins(prev: str) -> bool:
    """A ZWJ or ZWNJ after `prev` can change how a word is written: `prev` is a letter or mark of a script other than
    Latin (a Devanagari virama, for example). After a digit, a Latin letter, a space or punctuation it changes nothing."""
    return (ord(prev) > 0x7F and unicodedata.category(prev)[0] in "LM"
            and "LATIN " not in unicodedata.name(prev, ""))


def _drop_loose_joiners(text: str) -> str:
    if JOINERS[0] not in text and JOINERS[1] not in text:
        return text
    out: list[str] = []
    for ch in text:
        if ch in JOINERS and not (out and _joins(out[-1])):
            continue
        out.append(ch)
    return "".join(out)


def normalise(text: str) -> str:
    text = unicodedata.normalize("NFC", text.translate(_INVISIBLE))
    return _WS.sub(" ", _drop_loose_joiners(text)).strip()


def _word(ch: str) -> bool:
    """A letter, mark or digit of any script, "_", ZWJ or ZWNJ: a character that continues a word or number."""
    return ch == "_" or ch in JOINERS or unicodedata.category(ch)[0] in "LMN"


def _joined_before(text: str, i: int, first: str) -> bool:
    """True if the value starting at text[i] (first character `first`) continues what comes before it."""
    if i == 0:
        return False
    ch = text[i - 1]
    if _word(ch) and _word(first):
        return True
    if first.isdigit() and ch in "-−":                              # -31.6 is another number
        return True
    return first.isdigit() and ch in ".," and i >= 2 and text[i - 2].isdigit()   # 1.31.6, 1,250


def _joined_after(text: str, j: int, last: str) -> bool:
    """True if the value ending just before text[j] (last character `last`) continues into what follows."""
    if j >= len(text):
        return False
    ch = text[j]
    if _word(ch) and _word(last):
        return True
    return last.isdigit() and ch in ".," and j + 1 < len(text) and text[j + 1].isdigit()   # 31 in 31.6


def found(value: str, text: str) -> bool:
    """True if the normalised `value` appears in the normalised `text` as a whole value."""
    start = text.find(value)
    while start >= 0:
        end = start + len(value)
        if not _joined_before(text, start, value[0]) and not _joined_after(text, end, value[-1]):
            return True
        start = text.find(value, start + 1)
    return False


# --- the model's turn ----------------------------------------------------------------------------

def assistant_turn(completion: str) -> dict:
    """The one assistant message in a completion. Raises render.RenderError if it is not valid chat format v0, or
    if it runs on into another turn. The same reading as sft/tests/scorers.py parse_generation."""
    body = completion
    if body.endswith(T["endoftext"]):
        body = body[: -len(T["endoftext"])]
    if body.endswith(T["im_end"] + "\n"):
        body = body[:-1]
    if body.endswith(T["im_end"]):
        body = body[: -len(T["im_end"])]
    transcript = (f"{T['im_start']}system\n{render.EFFORT_PREFIX}1k{T['im_end']}\n"
                  f"{T['im_start']}assistant\n{body}{T['im_end']}\n{T['endoftext']}")
    messages = render.parse(transcript)["messages"]
    if len(messages) != 1 or messages[0].get("role") != "assistant":
        raise render.RenderError("the completion is not exactly one assistant turn")
    return messages[0]


# --- tasks -------------------------------------------------------------------------------------

def _no_duplicate_keys(pairs):
    if len({k for k, _ in pairs}) != len(pairs):
        raise ValueError("duplicate JSON key")
    return dict(pairs)


def _read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_no_duplicate_keys)


def _values(expected, key: str, where: str) -> tuple[str, ...]:
    values = expected.get(key) if isinstance(expected, dict) else None
    if not isinstance(values, list) or not values or not all(isinstance(x, str) and normalise(x) for x in values):
        raise ValueError(f"{where}: {key!r} must be a non-empty list of non-empty strings")
    return tuple(normalise(x) for x in values)


@lru_cache(maxsize=1024)
def _load(path: str, stamp: tuple) -> dict:
    d = Path(path)
    where = f"{d.name}/{EXPECTED}"
    meta, expected = _read_json(d / "task.json"), _read_json(d / EXPECTED)
    required, wrong = _values(expected, "required", where), _values(expected, "wrong", where)
    if set(required) & set(wrong):
        raise ValueError(f"{where}: a value is both required and wrong")
    return {"id": meta.get("id"), "effort": meta.get("effort", "1k"), "messages": _read_json(d / "messages.json"),
            "required": required, "wrong": wrong}


def load_task(task_dir: Path | str) -> dict:
    """The task, cached until one of its three files changes on disk."""
    d = Path(task_dir).resolve()
    return _load(str(d), tuple((s.st_mtime_ns, s.st_size) for s in ((d / f).stat() for f in TASK_FILES)))


def prompt_text(task_dir: Path | str) -> str:
    """The text the model is given: the rendered transcript, opened for the assistant's reply."""
    task = load_task(task_dir)
    text = render.render(list(task["messages"]), task["effort"])
    return text[: -len(T["endoftext"])] + f"{T['im_start']}assistant\n"


# --- the reward --------------------------------------------------------------------------------

def _not_text(completion) -> str | None:
    """Why a completion is not readable text, or None."""
    if not isinstance(completion, str):
        return "the completion is not text"
    try:
        completion.encode("utf-8")
    except UnicodeEncodeError:
        return "the completion is not valid Unicode text"  # a lone surrogate
    if _CONTROL.search(completion):
        return "the completion holds a control character"
    return None


def score(task: dict, completion: str) -> dict:
    out = {"task_id": task["id"], "reward": 0}
    problem = _not_text(completion)
    if problem:
        return {**out, "reason": problem}
    try:
        turn = assistant_turn(completion)
    except render.RenderError as exc:
        return {**out, "reason": f"not valid chat format: {exc}"}
    if turn.get("tool_calls"):
        return {**out, "reason": "made a tool call"}
    reply = normalise(turn.get("content", ""))
    if not reply:
        return {**out, "reason": "empty reply"}
    if len(reply) > MAX_REPLY_CHARS:
        return {**out, "reason": "reply too long"}
    if not all(found(v, reply) for v in task["required"]):
        return {**out, "reason": "a required value is missing or changed"}
    if any(found(v, reply) for v in task["wrong"]):
        return {**out, "reason": "the reply holds a wrong value"}
    return {**out, "reward": 1, "reason": "correct"}


def reward(task_dir: Path | str, completion: str) -> dict:
    return score(load_task(task_dir), completion)


def wrap(*values: str) -> str:
    """A short reply that quotes the given values: how known_outputs() and the lint write a completion."""
    return "The tool returned: " + "; ".join(values) + "."


def known_outputs(task_dir: Path | str) -> tuple[str, str]:
    """(a completion that must score 1, one that must score 0), from hidden/expected.json."""
    expected = _read_json(Path(task_dir) / EXPECTED)
    return wrap(*expected["required"]), wrap(expected["wrong"][0])


# --- task lint ---------------------------------------------------------------------------------

def _strings(values) -> bool:
    return isinstance(values, list) and bool(values) and all(isinstance(v, str) and normalise(v) for v in values)


def check_task(task_dir: Path | str) -> list[str]:
    """Problems with a task folder (empty list = fine)."""
    d = Path(task_dir)
    problems = [f"missing {f}" for f in TASK_FILES if not (d / f).is_file()]
    if problems:
        return problems
    try:
        meta, messages, expected = (_read_json(d / f) for f in TASK_FILES)
    except ValueError as exc:
        return [f"a task file is not valid JSON: {exc}"]
    if not (isinstance(meta, dict) and isinstance(expected, dict) and isinstance(messages, list)):
        return [f"task.json and {EXPECTED} must be JSON objects, messages.json a list"]
    for key in ("id", "title", "difficulty", "effort", "source", "author", "eligibility"):
        if not meta.get(key):
            problems.append(f"task.json lacks {key}")
    if meta.get("id") != d.name or not _NAME.match(d.name):
        problems.append("task.json id differs from the folder name, or the name has characters other than A-Z a-z 0-9 _ . -")
    if meta.get("difficulty") not in DIFFICULTIES:
        problems.append(f"difficulty must be one of {DIFFICULTIES}")
    if meta.get("effort") not in render.EFFORT_BUDGETS:
        problems.append(f"effort must be one of {tuple(render.EFFORT_BUDGETS)}")
    if meta.get("eligibility") not in ELIGIBILITY:
        problems.append(f"eligibility must be one of {ELIGIBILITY}")
    source = str(meta.get("source", ""))
    if not source.lower().startswith("original"):
        problems.append('source must start with "original" and name the author')
    if meta.get("eligibility") == "train" and _MODEL_WRITTEN.search(source):  # TSAI data rule, 3 Nov
        problems.append("a train task must be written by a person; its source names a model")
    if not _strings(expected.get("required")) or not _strings(expected.get("wrong")):
        problems.append(f"{EXPECTED} needs non-empty lists of non-empty strings: required and wrong")
    elif {normalise(v) for v in expected["required"]} & {normalise(v) for v in expected["wrong"]}:
        problems.append("a value is both required and wrong")
    if problems:
        return problems

    try:
        prompt_text(d)
    except render.RenderError as exc:
        return [f"messages.json is not valid chat format v0: {exc}"]
    if messages[-1].get("role") != "tool":
        problems.append("messages.json must end with a tool turn")
    if not any(m.get("role") == "assistant" and m.get("tool_calls") for m in messages):
        problems.append("messages.json has no assistant tool call")
    tool_text = [normalise(m["content"]) for m in messages if m.get("role") == "tool"]
    asked_text = [normalise(m.get("content", "")) for m in messages if m.get("role") in ("system", "user")]
    required = [normalise(v) for v in expected["required"]]
    wrong = [normalise(v) for v in expected["wrong"]]
    for v in required:
        if not any(found(v, t) for t in tool_text):
            problems.append(f"required value {v!r} is not in a tool result")
        if any(found(v, t) for t in asked_text):
            problems.append(f"required value {v!r} is in the system or user text, so it is not read from the tool")
    for v in wrong:
        if any(found(v, t) for t in tool_text):
            problems.append(f"wrong value {v!r} appears in a tool result")
    if problems:
        return problems

    task = load_task(d)
    good = score(task, wrap(*expected["required"]))
    if good["reward"] != 1:
        problems.append(f"the required values do not score 1: {good['reason']}")
    for w in expected["wrong"]:
        if score(task, wrap(w))["reward"] != 0:
            problems.append(f"wrong value {w!r} scores 1")
    return problems


def check_all(tasks_dir: Path = TASKS) -> dict[str, list[str]]:
    return {p.parent.name: check_task(p.parent) for p in sorted(tasks_dir.glob("*/task.json"))}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--reward", nargs=2, metavar=("TASK_DIR", "COMPLETION_FILE"))
    ap.add_argument("--prompt", metavar="TASK_DIR")
    ap.add_argument("--check-task", metavar="TASK_DIR")
    ap.add_argument("--check-all", action="store_true")
    args = ap.parse_args(argv)
    task_dir = (args.reward or [None])[0] or args.prompt or args.check_task
    if task_dir and not (Path(task_dir) / "task.json").is_file():
        print(f"task folder not found: {task_dir}", file=sys.stderr)
        return 2
    if args.reward:
        completion = Path(args.reward[1])
        if not completion.is_file():
            print(f"completion file not found: {completion}", file=sys.stderr)
            return 2
        print(json.dumps(reward(task_dir, completion.read_text(encoding="utf-8")), ensure_ascii=False))
        return 0
    if args.prompt:
        sys.stdout.write(prompt_text(task_dir))
        return 0
    if args.check_task:
        problems = check_task(task_dir)
        print("\n".join(problems) if problems else "task OK")
        return 1 if problems else 0
    if args.check_all:
        results = check_all()
        for name, problems in results.items():
            print(f"{name}: {'; '.join(problems) if problems else 'OK'}")
        return 1 if not results or any(results.values()) else 0
    ap.error("give --reward, --prompt, --check-task or --check-all")
    return 2


if __name__ == "__main__":
    sys.exit(main())
